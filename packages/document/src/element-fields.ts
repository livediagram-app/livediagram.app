const FIELD_SETS: ReadonlyMap<string, ReadonlySet<string>> = new Map(
  Object.entries(ELEMENT_FIELD_NAMES).map(([type, names]) => [type, new Set<string>(names)]),
);

// True when `key` is a stored field of elements of `type`; never for a prototype key.
export function isElementFieldName(type: Element['type'], key: string): boolean {
  return FIELD_SETS.get(type)?.has(key) ?? false;
}
