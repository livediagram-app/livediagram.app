// Writes apps/<app>/wrangler.preview.toml for one PR and tier
// (docs/specs/016-platform/blueprints/pr-previews.md "Config rewrite").
//
//   node scripts/config.ts --app router --pr 123 --tier preview
//   node scripts/config.ts --app api --pr 123 --tier full --d1-id <uuid>

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { parse, stringify } from 'smol-toml';

import { inTier, parseTier, type PreviewTier } from '../src/apps.ts';
import { previewConfig } from '../src/config.ts';
import { PreviewError } from '../src/errors.ts';
import { logLine } from '../src/log.ts';
import { PREVIEW_CONFIG_FILE, parsePrNumber, type PrNumber } from '../src/names.ts';
import { flags, required } from './args.ts';

export function appDir(app: string): string {
  return fileURLToPath(new URL(`../../../apps/${app}/`, import.meta.url));
}

/** Generates and writes one app's preview config; returns the path written. */
export function writePreviewConfig(
  app: string,
  pr: PrNumber,
  tier: PreviewTier,
  d1Id?: string,
): string {
  if (!inTier(app, tier))
    throw new PreviewError('not-in-tier', `${app} is not in a ${tier} preview`);
  const dir = appDir(app);
  const source = parse(readFileSync(`${dir}wrangler.toml`, 'utf8'));
  const config = previewConfig(source, { app, pr, tier, d1Id });
  const path = `${dir}${PREVIEW_CONFIG_FILE}`;
  writeFileSync(
    path,
    `# Generated by @livediagram/preview-env; never edit or commit.\n${stringify(config)}\n`,
  );
  const env = (config.env as { preview: { services?: { service: string }[] } }).preview;
  console.log(
    logLine('config', {
      app,
      pr,
      tier,
      services: (env.services ?? []).map((s) => s.service).join(',') || '-',
    }),
  );
  return path;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    const args = flags(process.argv.slice(2));
    writePreviewConfig(
      required(args, 'app'),
      parsePrNumber(required(args, 'pr')),
      parseTier(required(args, 'tier')),
      args.get('d1-id'),
    );
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}
