import type { Metadata } from 'next';

// Per-page SEO for a product's public sites: the metadata block (canonical + Open Graph + Twitter card).
// Marketing and the help centre each built their own and had drifted: help sent a `summary` Twitter card
// with no image and suffixed every title with the product's name, marketing a `summary_large_image` with
// the brand card and the title as given. One rule now (docs/specs/019-marketing/marketing-site.md "SEO and
// metadata" and docs/specs/018-help/help-app.md in each product): the title passes through verbatim, and
// every page carries the large brand card unless it ships its own. A product binds it to its own site with
// createPageMetadata (its `seo.ts`).

const LOCALE = 'en_GB';

// What a product's metadata is drawn from (its `site.ts`).
export type SeoSite = {
  // The canonical origin the brand card is served from.
  url: string;
  // The metadata siteName, and the card's alt text with the pitch.
  name: string;
  pitch: string;
};

export type PageMetadataInput = {
  title: string;
  description: string;
  // Canonical path, resolved against the app's metadataBase (the site's URL), so `/faq` becomes
  // `<origin>/faq`. A basePath app includes its prefix (help passes `/help/<category>/<article>/`).
  path: `/${string}`;
  // The OG siteName. Defaults to the site's name; the help centre names itself.
  siteName?: string;
  // Last-revised date for the page's content, emitted as the
  // `article:modified_time` OG tag (the companion to `og:type=article`).
  // Omitted, the tag is simply not emitted.
  modifiedTime?: Date;
  // Set when the page ships its OWN route-level opengraph-image /
  // twitter-image (marketing's per-page cards): the shared brand card
  // is then left off so it doesn't override the page's own.
  ownOgImage?: boolean;
  // A card of the page's own at a known absolute URL, used for both Open Graph and Twitter in place
  // of the brand card (the help centre's per-article cards, docs/specs/018-help/help-app.md "SEO").
  image?: { url: string; alt: string };
  // The OG type. `article` suits a content page; a hub or dashboard that is
  // the app's own front page (a Community gallery, the Telemetry
  // dashboard) is a `website`.
  type?: 'article' | 'website';
};

export function createPageMetadata(site: SeoSite) {
  // The shared brand card, generated by marketing's opengraph-image.tsx /
  // twitter-image.tsx and served at the origin root. Absolute, so it resolves
  // the same from any app whatever its basePath (the help centre has no card
  // of its own). Next only auto-attaches a file-convention image to a page that
  // declares no openGraph of its own; every page built here declares one, so
  // the card is referenced explicitly or it goes missing.
  const ogImage = {
    url: `${site.url}/opengraph-image`,
    width: 1200,
    height: 630,
    alt: `${site.name}: ${site.pitch}`,
  };
  const twitterImage = `${site.url}/twitter-image`;

  function pageMetadata({
    title,
    description,
    path,
    siteName = site.name,
    modifiedTime,
    ownOgImage = false,
    image,
    type = 'article',
  }: PageMetadataInput): Metadata {
    return {
      title,
      description,
      alternates: { canonical: path },
      openGraph: {
        type,
        url: path,
        siteName,
        title,
        description,
        locale: LOCALE,
        ...(ownOgImage
          ? {}
          : { images: [image ? { ...image, width: 1200, height: 630 } : ogImage] }),
        ...(modifiedTime ? { modifiedTime: modifiedTime.toISOString() } : {}),
      },
      twitter: {
        card: 'summary_large_image',
        title,
        description,
        ...(ownOgImage ? {} : { images: [image ? image.url : twitterImage] }),
      },
    };
  }

  return {
    pageMetadata,
    // The brand card alone, for a page whose og:url cannot be known at build time (a shell that
    // serves every post or document), so it still previews with an image rather than none.
    BRAND_OG_IMAGE: ogImage,
    BRAND_TWITTER_IMAGE: twitterImage,
  };
}
