import { describe, expect, it } from 'vitest';
import { TEST_PRODUCT, WORDED_PRODUCT } from '../testing/product';
import { createThreadTools, THREAD_CHANGES_MAX } from './thread-tools';

// docs/specs/015-api/mcp-server.md "Comment threads": the tools every canvas product declares in its own words.
describe('createThreadTools', () => {
  const { listThreads, changeThreads } = createThreadTools(TEST_PRODUCT, 'sketchId');

  it('names the tools as liveplanner’s, list a read and change destructive, in the product’s words', () => {
    expect([listThreads.mcp.tool, changeThreads.mcp.tool]).toEqual([
      'list_threads',
      'change_threads',
    ]);
    expect(listThreads.behaviour).toBe('read');
    expect(changeThreads.behaviour).toBe('destructive');
    expect(listThreads.mcp.title).toBe('List the comment threads on a sketch');
    expect(changeThreads.description).toContain('Generated by AI');
    const worded = createThreadTools(WORDED_PRODUCT, 'sketchId');
    expect(worded.changeThreads.mcp.title).toBe('Change the comment threads on a drawing');
  });

  it('takes the product’s id key, a tab and a status that defaults to open', () => {
    expect(listThreads.input.parse({ sketchId: 's1' })).toEqual({ sketchId: 's1', status: 'open' });
    expect(listThreads.input.safeParse({ sketchId: 's1', status: 'closed' }).success).toBe(false);
    expect(listThreads.input.safeParse({}).success).toBe(false);
  });

  it('takes each change by its op, refusing an unknown field, an empty or long text, and too many', () => {
    const parse = (changes: unknown[]) =>
      changeThreads.input.safeParse({ sketchId: 's1', changes }).success;
    expect(
      parse([
        { op: 'start', ref: 'a1', text: 'x' },
        { op: 'reply', ref: 'a1', tabId: 'Main', text: 'x' },
        { op: 'resolve', ref: 'a1' },
        { op: 'reopen', ref: 'a1' },
        { op: 'edit', ref: 'a1', comment: 'c1', text: 'y' },
        { op: 'delete', ref: 'a1', comment: 'c1' },
      ]),
    ).toBe(true);
    expect(parse([{ op: 'resolve', ref: 'a1', thread: 'x' }])).toBe(false);
    expect(parse([{ op: 'reply', ref: 'a1', text: '' }])).toBe(false);
    expect(parse([{ op: 'reply', ref: 'a1', text: 'x'.repeat(2001) }])).toBe(false);
    expect(parse([])).toBe(false);
    expect(
      parse(Array.from({ length: THREAD_CHANGES_MAX + 1 }, () => ({ op: 'resolve', ref: 'a' }))),
    ).toBe(false);
  });
});
