// @vitest-environment jsdom
import { render, screen } from '@testing-library/react';
import { describe, expect, it } from 'vitest';
import { AiCommentMark, EditedCommentMark } from './CommentMarks';

// docs/specs/024-agents/agent-presence.md "Comments": the marks every product's thread draws on a comment.
describe('the comment marks', () => {
  it('says Generated by AI, with its icon hidden from a screen reader', () => {
    const { container } = render(<AiCommentMark />);
    expect(screen.getByText('Generated by AI')).toHaveProperty('dataset.commentAi', '');
    expect(container.querySelector('svg')?.getAttribute('aria-hidden')).toBe('true');
  });

  it('says a changed comment was edited', () => {
    render(<EditedCommentMark />);
    expect(screen.getByText('· Edited')).toHaveProperty('dataset.commentEdited', '');
  });
});
