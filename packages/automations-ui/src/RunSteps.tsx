'use client';

// A run's steps, as the Audit Trail opens them and as the test shows them (liveplanner/docs/specs/026-plan/
// automations.md "The Automations screen": Audit Trail): the trigger with the bolt, each condition held (a tick) or
// not (a cross), each action done, already so (a dash) or failed, an AI step marked with the sparkle, and a branch's
// line with the lines of what it ran on inset under it (which lines, and how each reads, is the app's:
// kit.audit.inset). Every mark is said for screen readers. The last line offers the app's link to what the run was
// about.

import { CheckIcon, CloseIcon, SparkleIcon, lucideGlyph } from '@liveworkspace/ui';
import { lucideListTree, lucideMinus } from '@liveworkspace/icons/lucide';
import { BoltIcon } from './glyphs';
import { useAutomationsKit } from './kit-context';
import type { RunLine } from './types';

const AlreadyIcon = lucideGlyph(lucideMinus, 11);
const BranchIcon = lucideGlyph(lucideListTree, 11);

const MARK = 'inline-flex size-[18px] shrink-0 items-center justify-center rounded-full';

function Mark({ line }: { line: RunLine }) {
  if (line.kind === 'branch')
    return (
      <span
        aria-hidden
        className={`${MARK} ${line.ok ? 'bg-blue-100 text-blue-700 dark:bg-blue-500/20 dark:text-blue-300' : 'bg-red-100 text-red-700 dark:bg-red-500/20 dark:text-red-300'}`}
      >
        <BranchIcon />
      </span>
    );
  if (line.kind === 'trigger')
    return (
      <span
        aria-hidden
        className={`${MARK} bg-brand-100 text-brand-700 dark:bg-brand-500/20 dark:text-brand-300`}
      >
        <BoltIcon size={10} />
      </span>
    );
  if (line.kind === 'action' && line.already)
    return (
      <span
        aria-hidden
        className={`${MARK} bg-slate-100 text-slate-500 dark:bg-slate-800 dark:text-slate-400`}
      >
        <AlreadyIcon />
      </span>
    );
  return line.ok ? (
    <span
      aria-hidden
      className={`${MARK} bg-emerald-100 text-emerald-700 dark:bg-emerald-500/20 dark:text-emerald-300`}
    >
      <CheckIcon size={10} />
    </span>
  ) : (
    <span
      aria-hidden
      className={`${MARK} bg-red-100 text-red-700 dark:bg-red-500/20 dark:text-red-300`}
    >
      <CloseIcon size={10} />
    </span>
  );
}

const markWords = (line: RunLine) =>
  line.kind === 'branch'
    ? line.ok
      ? 'Branch: '
      : 'Branch, failed: '
    : line.kind === 'trigger'
      ? 'Trigger: '
      : line.kind === 'action' && line.already
        ? 'Already so: '
        : line.ok
          ? 'Held: '
          : 'Did not hold: ';

export function RunSteps({
  steps,
  openSubject,
}: {
  steps: readonly RunLine[];
  // Opens what the run was about; absent (a test, an app with no such link): no link.
  openSubject?: (() => void) | undefined;
}) {
  const { audit, sentence } = useAutomationsKit();
  const inset = audit.inset?.(steps);
  const lineText = (line: RunLine) =>
    line.kind === 'action' || line.kind === 'condition'
      ? sentence.gone(line.text, line.gone)
      : line.text;
  return (
    <ol data-run-steps="" className="flex flex-col gap-2.5">
      {steps.map((line, i) => {
        const under = inset?.[i] ?? null;
        return (
          <li
            key={i}
            data-run-related={under !== null ? '' : undefined}
            className={`flex items-center gap-2.5 text-[13px] text-slate-700 dark:text-slate-200 ${under !== null ? 'ml-7' : ''}`}
          >
            <Mark line={line} />
            <span className="min-w-0 flex-1">
              <span className="sr-only">{markWords(line)}</span>
              {/* The trigger's line opens with who did it ("Ana Costa moved it from To Do to Done"): their name in bold. */}
              {line.kind === 'trigger' && line.by && line.text.startsWith(line.by.name) ? (
                <>
                  <span className="font-semibold text-slate-900 dark:text-slate-50">
                    {line.by.name}
                  </span>
                  {line.text.slice(line.by.name.length)}
                </>
              ) : under !== null ? (
                under
              ) : (
                lineText(line)
              )}
              {line.kind === 'action' && line.already ? (
                <span className="text-slate-500 dark:text-slate-400"> (Already so)</span>
              ) : null}
              {/* An AI step's call: the sparkle, said as "Generated by AI". */}
              {line.kind === 'action' && line.ai ? (
                <span className="ml-1.5 inline-flex translate-y-[2px] text-brand-700 dark:text-brand-300">
                  <SparkleIcon size={12} aria-hidden />
                  <span className="sr-only"> Generated by AI</span>
                </span>
              ) : null}
            </span>
            {openSubject && audit.open && i === steps.length - 1 ? (
              <button
                type="button"
                onClick={openSubject}
                className="touch-target-y relative shrink-0 rounded text-[13px] font-medium text-brand-700 underline-offset-2 hover:text-brand-800 hover:underline dark:text-brand-300 dark:hover:text-brand-200"
              >
                {audit.open.label}
              </button>
            ) : null}
          </li>
        );
      })}
    </ol>
  );
}
