// "Fields and values"): what an edit operation's `set` may name, and the list its `unknown_field`
// refusal offers. `fieldsOf` fails the build when an element type gains a field this table does not
// list, and `satisfies` when a type has no list, so the table cannot drift from the types. The check,
// the lookup and the runs of fields many types list together are shared
// (@liveworkspace/element-model/element-fields); the lists and their order are this product's.

