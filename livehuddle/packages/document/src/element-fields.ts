type Unlisted<E, L extends readonly PropertyKey[]> = Exclude<keyof E, L[number]>;

const fieldsOf =
  <E extends Element>() =>
  <const L extends readonly (keyof E & string)[]>(
    names: L & ([Unlisted<E, L>] extends [never] ? unknown : { unlisted: Unlisted<E, L> }),
  ): L =>
    names;

