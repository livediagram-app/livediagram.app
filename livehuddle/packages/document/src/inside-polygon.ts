// Even-odd point-in-polygon, for the hit tests and the indicator placement that read a shape's drawn outline.
type Point = { x: number; y: number };

/** Even-odd: whether `p` lies inside the closed polyline. */
export function insidePolygon(p: Point, pts: readonly Point[]): boolean {
  let inside = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const a = pts[i]!;
    const b = pts[j]!;
    if (a.y > p.y !== b.y > p.y && p.x < ((b.x - a.x) * (p.y - a.y)) / (b.y - a.y) + a.x) {
      inside = !inside;
    }
  }
  return inside;
}
