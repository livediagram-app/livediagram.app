import { useEditorContext } from '@/app/document/[id]/EditorContext';
import type { CanvasProps } from '@/components/canvas/Canvas.types';
import type { LibraryShapeRef } from '@/lib/shape-library-dnd';
import type { useQuickConnectStart } from '@/hooks/canvas/useQuickConnectStart';
import { dropThenDisarm } from '@liveworkspace/workbench/lib/palette-drop';

// The Canvas props for putting things on the canvas (EditorCanvasHost): the palette's adds and drops,
// the event-storming board, the draw tools and their commits, the eraser, and quick connect.
export function useInsertCanvasProps({
  esBoardControls,
  dropLibraryShape,
  handleStartArrow,
}: {
  esBoardControls: CanvasProps['esBoardControls'];
  dropLibraryShape: (ref: LibraryShapeRef, at: { x: number; y: number }) => void;
  handleStartArrow: ReturnType<typeof useQuickConnectStart>['handleStartArrow'];
}) {
  const {
    addAnnotation,
    addArrow,
    addAvatar,
    addBanner,
    addCallout,
    addHeader,
    addHero,
    addIcon,
    addSticker,
    addImage,
    addLinkCard,
    addVideo,
    addProcess,
    addFlowchart,
    addShape,
    addStatRow,
    addSticky,
    esBoard,
    addNextNote,
    readPhotoFile,
    dropBoardFile,
    createBlocked,
    addTable,
    addTechIcon,
    insertLibraryShape,
    addText,
    beginErase,
    beginFreehand,
    beginHighlighter,
    beginMarker,
    beginShapePen,
    beginPolygon,
    cancelDrawShape,
    commitDraw,
    commitFreehand,
    commitPolygon,
    commitPath,
    paintBucket,
    commitPathEdit,
    styleNewElement,
    dropIconOnElement,
    dropPaletteItem,
    isReadOnly,
    openCellLinkPicker,
    pendingDraw,
    spawnConnectSelected,
  } = useEditorContext();
  return {
    onEraseStart: isReadOnly ? undefined : beginErase,
    onAddShape: addShape,
    onAddIcon: addIcon,
    onAddSticker: addSticker,
    onAddTechIcon: addTechIcon,
    onInsertLibraryShape: (item) => void insertLibraryShape(item),
    onDropIcon: isReadOnly ? undefined : dropIconOnElement,
    onLinkCell: isReadOnly ? undefined : openCellLinkPicker,
    onAddTable: addTable,
    onAddAnnotation: addAnnotation,
    onAddLinkCard: addLinkCard,
    onAddVideo: addVideo,
    onAddBanner: addBanner,
    onAddHero: addHero,
    onAddHeader: addHeader,
    onAddCallout: addCallout,
    onAddStatRow: addStatRow,
    onAddProcess: addProcess,
    onAddFlowchart: addFlowchart,
    onAddAvatar: addAvatar,
    onAddText: addText,
    onAddSticky: addSticky,
    esBoard: esBoard,
    esBoardControls: esBoardControls,
    onAddNextNote: createBlocked ? undefined : addNextNote,
    onDropPhoto: readPhotoFile,
    onDropFile: isReadOnly ? undefined : dropBoardFile,
    onDropLibraryShape: isReadOnly ? undefined : dropLibraryShape,
    createBlocked: createBlocked,
    onAddImage: addImage,
    onAddArrow: addArrow,
    onBeginFreehand: beginFreehand,
    onBeginHighlighter: beginHighlighter,
    onBeginMarker: beginMarker,
    onBeginShapePen: beginShapePen,
    onBeginPolygon: beginPolygon,
    pendingDraw: pendingDraw,
    onCommitDraw: commitDraw,
    onCommitFreehand: commitFreehand,
    onCommitPolygon: commitPolygon,
    onCommitPath: commitPath,
    onPaintBucket: paintBucket,
    onCommitPathEdit: commitPathEdit,
    onDressPath: styleNewElement,
    onCancelDraw: cancelDrawShape,
    onDropPalette: dropThenDisarm(dropPaletteItem, cancelDrawShape),
    onSpawnConnect: spawnConnectSelected,
    onStartArrow: handleStartArrow,
    onStartPencil: beginFreehand,
  } satisfies Partial<CanvasProps>;
}
