export const PAGE_DESIGN_BY_ID = Object.fromEntries(PAGE_DESIGNS.map((d) => [d.id, d])) as Record<
  PageDesignId,
  PageDesignMeta
>;

/** The designs of a family, in catalogue order. */
export function designsOfFamily(family: PageDesignFamily): readonly PageDesignMeta[] {
  return PAGE_DESIGNS.filter((d) => d.family === family);
}

/** A design's name, or "None". */
export function pageDesignLabel(id: string | undefined): string {
  return id && isPageDesignId(id) ? PAGE_DESIGN_BY_ID[id].label : 'None';
}
