export function isPageDesignId(v: unknown): v is PageDesignId {
  return typeof v === 'string' && (PAGE_DESIGN_IDS as readonly string[]).includes(v);
}

/** A control a design offers beyond the ones every design has (Colours, Intensity, Safe area, Grain). */
export type PageDesignControl = 'scale' | 'angle' | 'focus' | 'seed' | 'blur';

export type PageDesignStyle = { id: string; label: string };

export type PageDesignMeta = {
  id: PageDesignId;
  label: string;
  family: PageDesignFamily;
  controls: readonly PageDesignControl[];
  // Its own options, the first its default.
  variants?: readonly PageDesignStyle[];
  defaults?: {
    intensity?: number;
    angle?: number;
    focus?: [number, number];
    blur?: number;
    calm?: number;
  };
  animates?: true;
  // Can be drawn as one strip across consecutive pages.
  flows?: true;
  // How much of the page it covers at full intensity, 0 to 1: what the contrast guard weighs.
  busy: number;
  // Words that suit it, for picking a design for a tab's words.
  keywords: readonly string[];
};

