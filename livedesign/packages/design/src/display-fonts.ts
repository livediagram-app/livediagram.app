// The display library (docs/specs/004-interface-design/fonts.md "The display library", docs/specs/007-editor/
// logo-pages.md "Display faces"): a second closed list of typefaces, offered for text on a logo page beside the
// eleven every page has. A wordmark is set at 60 px and up, where a display face is the point; the eleven are tuned
// for 12 px labels. Pure data: one entry per face, sorted by category then label.
//
// Every family is on Google Fonts under the SIL Open Font License 1.1 (checked against the google/fonts repository's
// ofl/ folder, 15 November 2026), fetched from fonts.googleapis.com as the eleven are and never bundled. None is one
// of the eleven: their ids are storage keys (caveat, abril-fatface) that already draw other faces. Each loads the
// weights it has of 400, 500 and 700; a one-weight face loads its one (Google's default, 400).

