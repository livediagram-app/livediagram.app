// Comment threads at the foot of a page (docs/specs/030-knowledgebase/page-comments.md) on the wire: the threads a
// page holds, one change to them, and the room op that tells everyone on the page. Types and limits only; the api
// stores them (apps/api/src/knowledge/page-threads.ts).

/** The most threads a page holds, and comments a thread. */
export const PAGE_THREADS_MAX = 500;
export const PAGE_THREAD_COMMENTS_MAX = 200;

/** One comment. `by` is its author's collab key (the platform's public id for a person), so a client knows its
 *  own comments without anyone's account id on the wire. */
export type PageComment = {
  id: string;
  text: string;
  createdAt: number;
  authorName: string;
  authorColor: string;
  by: string;
  editedAt?: number;
  /** Written by an agent: shown as Generated by AI. */
  ai?: true;
};

export type PageThread = {
  id: string;
  tab: string;
  createdAt: number;
  updatedAt: number;
  resolved: boolean;
  /** Who resolved it, by name, and when; absent while open. */
  resolvedBy?: string;
  resolvedAt?: number;
  comments: PageComment[];
};

/** `GET .../pages/<tab>/threads`: every thread on the page, oldest first. */
export type PageThreadsResponse = { threads: PageThread[] };

/** `POST .../pages/<tab>/threads`: one change. `start` makes a thread; the rest name one. */
export type PageThreadChange =
  | { op: 'start'; text: string; name?: string }
  | { op: 'reply'; thread: string; text: string; name?: string }
  | { op: 'resolve'; thread: string }
  | { op: 'reopen'; thread: string }
  | { op: 'edit'; thread: string; comment: string; text: string }
  | { op: 'delete'; thread: string; comment: string };

/** The thread as it stands after the change, or `removed` when its last comment went. */
export type PageThreadChangeResponse = { thread: PageThread } | { removed: string };

/** The room op the api sends after each change (from the system; a client never sends one). */
export type PageThreadOp =
  | { kind: 'page-thread'; tabId: string; thread: PageThread }
  | { kind: 'page-thread'; tabId: string; threadId: string; removed: true };
