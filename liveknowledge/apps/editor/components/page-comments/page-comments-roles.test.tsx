// @vitest-environment jsdom
// docs/specs/030-knowledgebase/page-comments.md "Share roles", as the editor draws them: an Editor, a Participant and
// an edit link's guest (each `can.takePart`) start threads, reply, resolve and reopen, and edit or delete only their own
// comments; a Viewer and a view link's visitor read, and see nothing at all on a page with no threads. The api's half
// is apps/api/src/routes/knowledge-thread-routes.test.ts.
import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import { describe, expect, it, vi } from 'vitest';
import type { PageThread } from '@liveknowledge/api-schema';
import { resolveEditorCapabilities } from '@/lib/editor-capabilities';
import { PageCommentsView } from './PageComments';

const NOW = Date.UTC(2026, 10, 21, 12);
const mine = {
  id: 'c1',
  text: 'Is the Friday rule still true?',
  createdAt: NOW - 60_000,
  authorName: 'Priya',
  authorColor: '#0ea5e9',
  by: 'key_me',
};
const theirs = {
  id: 'c2',
  text: 'Yes, since March.',
  createdAt: NOW - 30_000,
  authorName: 'Sam',
  authorColor: '#f97316',
  by: 'key_sam',
  ai: true as const,
};
const OPEN: PageThread = {
  id: 't1',
  tab: 'p1',
  createdAt: NOW - 60_000,
  updatedAt: NOW,
  resolved: false,
  comments: [mine, theirs],
};
const RESOLVED: PageThread = {
  ...OPEN,
  id: 't2',
  resolved: true,
  resolvedBy: 'Sam',
  resolvedAt: NOW - 3_600_000,
  comments: [theirs],
};

const LEVELS = {
  editor: 'edit',
  participant: 'participate',
  'edit-link guest': 'participate',
  viewer: 'view',
  'view-link visitor': 'view',
} as const;

function draw(
  who: keyof typeof LEVELS,
  threads: readonly PageThread[],
  change = vi.fn(async () => true),
) {
  const canWrite = resolveEditorCapabilities(LEVELS[who]).takePart;
  const view = render(
    <PageCommentsView
      status="ready"
      threads={threads}
      canWrite={canWrite}
      ownKey="key_me"
      now={NOW}
      change={change}
    />,
  );
  return { ...view, change };
}

describe('the comments at a page’s foot, by role', () => {
  for (const who of ['editor', 'participant', 'edit-link guest'] as const)
    it(`lets ${who === 'editor' ? 'an' : 'a'} ${who} start a thread, reply and resolve`, async () => {
      const { change } = draw(who, [OPEN]);
      expect(screen.getByRole('heading', { name: /Comments/ }).textContent).toBe('Comments1');
      // With a thread to answer, a new thread is behind a quiet button; the thread ends in its own reply line.
      expect(screen.queryByLabelText('Add a comment')).toBeNull();
      fireEvent.click(screen.getByRole('button', { name: 'Start a New Thread' }));
      fireEvent.change(screen.getByLabelText('Add a comment'), { target: { value: 'New point' } });
      fireEvent.click(screen.getByRole('button', { name: 'Comment' }));
      await waitFor(() => expect(change).toHaveBeenCalledWith({ op: 'start', text: 'New point' }));
      fireEvent.click(screen.getByRole('button', { name: 'Resolve' }));
      expect(change).toHaveBeenCalledWith({ op: 'resolve', thread: 't1' });
      fireEvent.change(screen.getByLabelText('Reply'), { target: { value: 'Agreed' } });
      fireEvent.keyDown(screen.getByLabelText('Reply'), { key: 'Enter', ctrlKey: true });
      await waitFor(() =>
        expect(change).toHaveBeenCalledWith({ op: 'reply', thread: 't1', text: 'Agreed' }),
      );
    });

  it('offers Edit and Delete on one’s own comment only, and asks before deleting', async () => {
    const { change } = draw('participant', [OPEN]);
    expect(screen.getAllByRole('button', { name: 'Edit comment' })).toHaveLength(1);
    expect(screen.getAllByRole('button', { name: 'Delete comment' })).toHaveLength(1);
    fireEvent.click(screen.getByRole('button', { name: 'Delete comment' }));
    expect(change).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole('button', { name: 'Delete' }));
    expect(change).toHaveBeenCalledWith({ op: 'delete', thread: 't1', comment: 'c1' });
    fireEvent.click(screen.getByRole('button', { name: 'Edit comment' }));
    fireEvent.change(screen.getByLabelText('Edit your comment'), { target: { value: 'Is it?' } });
    fireEvent.click(screen.getByRole('button', { name: 'Save' }));
    await waitFor(() =>
      expect(change).toHaveBeenCalledWith({
        op: 'edit',
        thread: 't1',
        comment: 'c1',
        text: 'Is it?',
      }),
    );
  });

  it('marks an agent’s comment as Generated by AI', () => {
    draw('viewer', [OPEN]);
    expect(document.querySelectorAll('[data-comment-ai]')).toHaveLength(1);
  });

  for (const who of ['viewer', 'view-link visitor'] as const)
    it(`lets a ${who} read, with nothing to press`, () => {
      draw(who, [OPEN, RESOLVED]);
      expect(screen.getByText('Is the Friday rule still true?')).toBeTruthy();
      expect(screen.queryByLabelText('Add a comment')).toBeNull();
      for (const name of ['Reply', 'Resolve', 'Reopen', 'Edit comment', 'Delete comment'])
        expect(screen.queryByRole('button', { name })).toBeNull();
    });

  it('shows a Viewer nothing on a page with no threads, and a writer the empty state and the composer', () => {
    const { container, unmount } = draw('viewer', []);
    expect(container.innerHTML).toBe('');
    unmount();
    draw('participant', []);
    expect(
      screen.getByText('Questions, corrections and context for this page go here.'),
    ).toBeTruthy();
    expect(screen.getByRole('button', { name: 'Comment' }).hasAttribute('disabled')).toBe(true);
  });

  it('folds resolved threads, says who resolved them, and reopens one', () => {
    const { change } = draw('editor', [OPEN, RESOLVED]);
    const folded = document.querySelector('[data-resolved-threads]') as HTMLDetailsElement;
    expect(folded.open).toBe(false);
    expect(folded.querySelector('summary')!.textContent).toContain('1 Resolved');
    expect(folded.textContent).toContain('Resolved by Sam, 1 hour ago');
    fireEvent.click(screen.getByRole('button', { name: 'Reopen' }));
    expect(change).toHaveBeenCalledWith({ op: 'reopen', thread: 't2' });
  });

  it('draws nothing before the read lands', () => {
    const { container } = render(
      <PageCommentsView
        status="loading"
        threads={[]}
        canWrite
        ownKey={null}
        now={NOW}
        change={vi.fn()}
      />,
    );
    expect(container.innerHTML).toBe('');
  });
});
