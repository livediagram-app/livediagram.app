// Writes Better Auth's schema as a D1 migration. Runs the same options the Worker uses
// against an empty in-memory SQLite and saves the SQL Better Auth would apply to it.
//
//   pnpm db:generate            -> migrations/0001_better_auth.sql
//
// After a Better Auth upgrade or a plugin change, delete nothing: point this at a SQLite
// copy of the current schema (it only emits what is missing) and save the next number.
import { writeFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import { getMigrations } from 'better-auth/db/migration';
import { authOptions } from '../src/auth-options.ts';

const out = process.argv[2] ?? new URL('../migrations/0001_better_auth.sql', import.meta.url);

const options = authOptions(
  {
    baseUrl: 'http://localhost:8787',
    secret: 'schema-only-secret-schema-only-secret',
    resources: [],
    turnstileSecretKey: 'unused',
    adminToken: '',
    sendCode: async () => {},
  },
  new DatabaseSync(':memory:'),
);

const { compileMigrations } = await getMigrations(options);
const sql = await compileMigrations();
writeFileSync(
  out,
  `-- Generated by scripts/generate-migration.ts (better-auth). Do not edit by hand.\n${sql}\n`,
);
console.log(`wrote ${out}`);
