const lookup = elementFieldLookup(ELEMENT_FIELD_NAMES);

// True when `key` is a stored field of elements of `type`; never for a prototype key.
export function isElementFieldName(type: Element['type'], key: string): boolean {
  return lookup(type, key);
}
