// The card thread verbs (docs/specs/015-api/cli.md "Commands", docs/specs/026-plan/plan-agents.md "Comment
// threads"): list a plan's card comment threads, start one on a card, reply, resolve, reopen, and edit or delete a
// comment the agent wrote, through the Plan engine the MCP's list_threads and change_threads share. A card is named
// by its number (#12), a thread by its id, an id prefix or its title, a comment by its id or an id prefix.

import { z } from 'zod';
import { defineVerb, VerbRefusal, type VerbContext } from '../define';
import {
  applyThreadChanges,
  readThreadsState,
  threadListing,
  THREAD_STATUSES,
  type ThreadChange,
} from '../plan/card-threads';
import { columns, projectOf } from './shared';

const projectArg = z.string().describe('A name, id prefix or liveplanner URL');
const itemArg = z.string().describe('The card, by its number (#12) or an id prefix');
const threadArg = z.string().describe('The thread, by its id, an id prefix or its title');
const commentArg = z.string().describe('The comment, by its id or an id prefix');
const textArg = z.string().min(1).describe('The comment');

const LS_HINT = 'list the threads with: liveplanner thread ls <project> --status all';

const commentOut = z.object({
  id: z.string(),
  author: z.string(),
  at: z.string(),
  text: z.string(),
  ai: z.literal(true).optional(),
  edited: z.literal(true).optional(),
});

const threadOut = z.object({
  id: z.string(),
  title: z.string(),
  state: z.enum(['open', 'resolved']),
  resolvedBy: z.string().optional(),
  cards: z.array(z.string()),
  comments: z.array(commentOut),
});

const appliedOut = z.object({ applied: z.array(z.string()) });

// One change through the engine, a refusal as the verb's.
async function changeOne(
  ctx: VerbContext,
  projectRef: string,
  change: ThreadChange,
): Promise<{ applied: string[] }> {
  const project = await projectOf(ctx, projectRef);
  const state = await readThreadsState(ctx.api, project.id);
  const result = await applyThreadChanges(ctx.api, project.id, [change], state);
  if (result.refusal)
    throw new VerbRefusal({
      status: result.refusal.code === 'forbidden' ? 403 : 400,
      code: result.refusal.code,
      message: result.refusal.message,
      hint: LS_HINT,
    });
  return { applied: result.applied };
}

const appliedText = ({ applied }: { applied: string[] }) => applied;

export const threadLs = defineVerb({
  id: 'thread.ls',
  summary: 'The comment threads on a plan’s cards',
  description:
    'Lists the card comment threads of a plan, open ones by default, or one card’s: each thread’s id, state, ' +
    'title and cards, then its comments (an agent’s marked [AI]).',
  behaviour: 'read',
  input: z.object({
    project: projectArg,
    item: itemArg.optional(),
    status: z.enum(THREAD_STATUSES).default('open').describe('open, resolved or all'),
  }),
  output: z.object({ threads: z.array(threadOut) }),
  listKey: 'threads',
  run: async (ctx, input) => {
    const project = await projectOf(ctx, input.project);
    const state = await readThreadsState(ctx.api, project.id);
    const listing = threadListing(state, project.id, input.status, input.item);
    if (!listing.ok)
      throw new VerbRefusal({
        status: 404,
        code: 'item_unknown',
        message: listing.message,
        hint: 'list the cards with: liveplanner item ls <project>',
      });
    return { threads: listing.threads };
  },
  text: ({ threads }) =>
    threads.length === 0
      ? ['No threads.']
      : threads.flatMap((t) => [
          ...columns([
            [
              t.id,
              t.state === 'resolved'
                ? `resolved${t.resolvedBy ? ` by ${t.resolvedBy}` : ''}`
                : 'open',
              JSON.stringify(t.title),
              t.cards.join(', '),
            ],
          ]),
          ...t.comments.map(
            (c) =>
              `  ${c.id} ${c.author}${c.ai ? ' [AI]' : ''}${c.edited ? ' (edited)' : ''}: ${c.text.replace(/\s+/g, ' ')}`,
          ),
        ]),
  quiet: ({ threads }) => threads.map((t) => t.id),
  cli: {
    positionals: ['project'],
    examples: [
      'liveplanner thread ls "Sprint 14"',
      'liveplanner thread ls 3f9c --item "#12" --status all',
    ],
    prints: 'a line a thread (id, state, title, cards), then its comments indented, one a line',
  },
});

export const threadStart = defineVerb({
  id: 'thread.start',
  summary: 'Start a comment thread on a card',
  description:
    'Starts a new comment thread on a card with its first comment, titled from your name and the comment. ' +
    'The comment is marked Generated by AI.',
  behaviour: 'write',
  input: z.object({ project: projectArg, item: itemArg, text: textArg }),
  output: appliedOut,
  run: (ctx, input) =>
    changeOne(ctx, input.project, { op: 'start', item: input.item, text: input.text }),
  text: appliedText,
  cli: {
    positionals: ['project', 'item', 'text'],
    examples: [
      'liveplanner thread start "Sprint 14" "#12" "The cart resets on route change."',
      'liveplanner thread start 3f9c 12 "Can we ship this behind a flag?"',
    ],
    prints: '+ thread <id> "<title>" on #<number>',
  },
});

