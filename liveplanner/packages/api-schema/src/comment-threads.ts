// Comment threads as the api lists them across a project (docs/specs/024-agents/agent-presence.md "Comments",
// blueprint "REST"): one thread per element, with the element's ref and label, so an agent can read the
// conversation without reading the tab. The statuses and the text cap are liveworkspace's
// (@liveworkspace/api-schema/comment-threads). The thread is declared here: a project's can also sit on a
// Sheet cell, and the api's OpenAPI document names it `ProjectCommentThread`.

import type { CommentMention, ReactionSummary } from '@liveplanner/project';

export {
  COMMENT_LIST_STATUSES,
  COMMENT_TEXT_MAX,
  isCommentListStatus,
  type CommentListStatus,
} from '@liveworkspace/api-schema/comment-threads';

export type ProjectCommentThread = {
  tabId: string;
  tabName: string;
  elementId: string;
  ref: string;
  label: string | null;
  // A Sheet cell's thread (docs/specs/029-sheets/sheet.md "Cell comments"): its cell key (`rowId:colId`), and its
  // A1 when the sheet is stored and the cell still on it.
  cell?: string;
  cellRef?: string;
  resolved: boolean;
  comments: {
    id: string;
    text: string;
    createdAt: number;
    authorName: string;
    authorColor: string;
    mentions?: CommentMention[];
    // Who reacted, one entry per emoji used (docs/specs/012-collaboration/comment-reactions.md). Absent when none.
    reactions?: ReactionSummary[];
    // The caller's own comments only.
    authorId?: string;
    tokenId?: string;
    // Written by an agent: shown as Generated by AI.
    ai?: true;
    editedAt?: number;
  }[];
};

// GET /api/projects/:id/comments?status=open|resolved|all.
export type ProjectCommentsResponse = { threads: ProjectCommentThread[] };
