// @vitest-environment jsdom
import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import type { ItemHistoryEntry } from '@liveplanner/items';
import type { CardThreads as CardThreadsValue } from '@/hooks/plan/useCardThreads';
import { writeLocalStorageValue } from '@liveworkspace/workbench/hooks/ui/useLocalStorageValue';
import { CardThreads } from './CardThreads';
import { CARD_ACTIVITY_KEY, activityFeed } from './CardActivity';
import { PlanProvider, type PlanContextValue } from '../PlanContext';
import { card, contextOf, fakeThreads, PLAN, Provide, thread } from './thread-test-kit';

// A card's activity in its panel (docs/specs/026-plan/items.md "History" "Where it shows"): the switch, the rows
// interleaved with the open threads by time, Show N More, the notes, the read on open and on a change, and that a
// Viewer reads it as anyone does.

const fetchItemHistory = vi.fn<(...args: unknown[]) => unknown>();
vi.mock('@/lib/api/item-history', () => ({
  fetchItemHistory: (...args: unknown[]) => fetchItemHistory(...args),
}));
const track = vi.fn<(...args: unknown[]) => void>();
vi.mock('@/lib/telemetry', () => ({ track: (...args: unknown[]) => track(...args) }));

const SCOPE = { ownerId: 'owner-me', projectId: PLAN, shareCode: null, tabId: null };
const NOW = Date.now();
const entry = (minsAgo: number, extra: Partial<ItemHistoryEntry> = {}): ItemHistoryEntry => ({
  at: NOW - minsAgo * 60_000,
  by: { name: 'Ada King', color: '#f97316' },
  changes: [{ kind: 'moved', from: 'doing', to: 'review' }],
  ...extra,
});

const plan = {
  items: new Map(),
  types: [],
  statusNames: new Map([
    ['doing', 'In Progress'],
    ['review', 'Review'],
  ]),
} as unknown as PlanContextValue;

const flush = () => act(async () => {});

function show(
  threads = [thread('th-a', { updatedAt: NOW - 30 * 60_000 })],
  extra: Parameters<typeof contextOf>[1] = {},
  item = card(),
) {
  const fake = fakeThreads(threads);
  const value = { ...fake.threads, scope: SCOPE } as unknown as CardThreadsValue;
  const ui = (it = item) => (
    <PlanProvider value={plan}>
      <Provide value={contextOf(value, extra)}>
        <CardThreads item={it} />
      </Provide>
    </PlanProvider>
  );
  const view = render(ui());
  return { rerender: (it: typeof item) => view.rerender(ui(it)) };
}

beforeEach(() => {
  // The switch starts on in every test; the store keeps what a test before it wrote.
  writeLocalStorageValue(CARD_ACTIVITY_KEY, 'on');
  fetchItemHistory.mockReset();
  track.mockReset();
});
afterEach(cleanup);

describe('the activity feed', () => {
  it('interleaves the card’s activity with its open threads by time, newest first', async () => {
    fetchItemHistory.mockResolvedValue([
      entry(5, { mine: true }),
      entry(60, {
        by: { name: 'Bo', color: '#16a34a' },
        tag: 'ai',
        changes: [{ kind: 'flagged' }],
      }),
      entry(90, { tag: 'undo', changes: [{ kind: 'archived' }] }),
    ]);
    show();
    await flush();
    expect(fetchItemHistory).toHaveBeenCalledWith(SCOPE, 'card-1');
    const list = screen.getByRole('list', { name: 'Open threads and activity' });
    const rows = within(list)
      .getAllByRole('listitem')
      .map((li) =>
        li.hasAttribute('data-activity')
          ? li.querySelector('p')!.textContent
          : `thread ${li.getAttribute('data-thread')}`,
      );
    expect(rows[0]).toMatch(/^You moved this from In Progress to Review · 5m ago$/);
    expect(rows[1]).toBe('thread th-a');
    expect(rows[2]).toMatch(/^BoGenerated by AI flagged this · 1h ago$/);
    expect(rows[3]).toMatch(/^Ada King archived this \(Undo\) · 1h ago$/);
  });

  it('turns off and on from the switch, remembered in this browser', async () => {
    fetchItemHistory.mockResolvedValue([entry(5)]);
    show();
    await flush();
    const toggle = screen.getByRole('switch', { name: 'Activity' });
    expect(toggle.getAttribute('aria-checked')).toBe('true');
    fireEvent.click(toggle);
    expect(track).toHaveBeenCalledWith('Plan', 'Toggled', 'ActivityOff');
    expect(localStorage.getItem(CARD_ACTIVITY_KEY)).toBe('off');
    expect(document.querySelector('[data-activity]')).toBeNull();
    expect(screen.getByRole('list', { name: 'Open threads' })).toBeTruthy();
    fireEvent.click(toggle);
    expect(track).toHaveBeenCalledWith('Plan', 'Toggled', 'ActivityOn');
    await flush();
    expect(document.querySelectorAll('[data-activity]')).toHaveLength(1);
  });

  it('reads nothing while it is off', async () => {
    writeLocalStorageValue(CARD_ACTIVITY_KEY, 'off');
    show();
    await flush();
    expect(fetchItemHistory).not.toHaveBeenCalled();
  });

  it('holds rows past the eighth under Show N More', async () => {
    fetchItemHistory.mockResolvedValue(Array.from({ length: 11 }, (_, i) => entry(i + 1)));
    show([]);
    await flush();
    expect(document.querySelectorAll('[data-activity]')).toHaveLength(8);
    fireEvent.click(screen.getByRole('button', { name: 'Show 3 More' }));
    expect(document.querySelectorAll('[data-activity]')).toHaveLength(11);
    expect(screen.queryByRole('button', { name: /More$/ })).toBeNull();
  });

  it('shows the card’s activity under the empty state when it has no threads', async () => {
    fetchItemHistory.mockResolvedValue([
      entry(1, { changes: [{ kind: 'created', status: 'doing' }] }),
    ]);
    show([]);
    await flush();
    expect(screen.getByText('No threads yet')).toBeTruthy();
    expect(document.querySelector('[data-activity]')!.textContent).toMatch(
      /created this card in In Progress/,
    );
  });

  it('reads it again, after a pause, when the card changes', async () => {
    vi.useFakeTimers();
    fetchItemHistory.mockResolvedValue([entry(5)]);
    const view = show();
    await flush();
    expect(fetchItemHistory).toHaveBeenCalledTimes(1);
    view.rerender({ ...card(), rev: 2 });
    view.rerender({ ...card(), rev: 3 });
    await act(async () => {
      vi.advanceTimersByTime(500);
    });
    expect(fetchItemHistory).toHaveBeenCalledTimes(2);
    vi.useRealTimers();
  });

  it('answers a Viewer as anyone: the rows, no New Thread', async () => {
    fetchItemHistory.mockResolvedValue([entry(5)]);
    show([], { canComment: false, isEditor: false });
    await flush();
    expect(document.querySelectorAll('[data-activity]')).toHaveLength(1);
    expect(screen.queryByRole('button', { name: 'New Thread' })).toBeNull();
    expect(screen.getByRole('switch', { name: 'Activity' })).toBeTruthy();
  });
});

describe('the notes', () => {
  it('says when nothing is recorded yet', async () => {
    fetchItemHistory.mockResolvedValue([]);
    show();
    await flush();
    expect(screen.getByText('No activity recorded yet.')).toBeTruthy();
  });

  it('says a This Browser plan keeps no history', async () => {
    fetchItemHistory.mockResolvedValue('offline');
    show();
    await flush();
    expect(screen.getByText('Plans in This Browser keep no card history.')).toBeTruthy();
  });

  it('says a read failed, and tries again', async () => {
    fetchItemHistory.mockRejectedValueOnce(new Error('down')).mockResolvedValue([entry(2)]);
    show();
    await flush();
    expect(screen.getByText(/Couldn’t load this card’s activity/)).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: 'Try Again' }));
    await flush();
    expect(document.querySelectorAll('[data-activity]')).toHaveLength(1);
  });

  it('draws no switch without a place to read from', () => {
    const { threads } = fakeThreads([]);
    render(
      <Provide value={contextOf(threads)}>
        <CardThreads item={card()} />
      </Provide>,
    );
    expect(screen.queryByRole('switch')).toBeNull();
  });
});

describe('activityFeed', () => {
  it('keeps every thread, and only the newest activity rows', () => {
    const t = thread('th-old', { updatedAt: 1 });
    const { rows, hidden } = activityFeed([t], [entry(1), entry(2), entry(3)], 2);
    expect(rows.map((r) => r.kind)).toEqual(['activity', 'activity', 'thread']);
    expect(hidden).toBe(1);
  });
});
