// @vitest-environment jsdom
import { cleanup, render, screen } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { itemAssistantFor, type Item, type ItemPerson } from '@liveplanner/items';
import type { CardThread } from '@liveplanner/project';
import { ASSISTANT_NOTE_MAX, assistantProgress, spanWords } from './assistant-progress';
import { AssistantProgress } from './AssistantProgress';
import { PersonDisc, assistantLabel } from './PersonDisc';
import { AssignMenu } from './SelectionBarMenus';

// docs/specs/026-plan/items.md "The AI mark", "Progress on the card".
vi.mock('./threads/CardThreadsContext', () => ({
  useCardThreadsContext: () =>
    threadsNow === NO_CONTEXT ? undefined : { threads: { threadsOf: () => threadsNow } },
}));
const NO_CONTEXT: CardThread[] = [];
let threadsNow: CardThread[] = [];
afterEach(() => {
  cleanup();
  threadsNow = [];
});

const MIN = 60_000;
const NOW = 1_800_000_000_000;
const THOMAS: ItemPerson = { id: 'a1b2c3d4e5f6a1b2c3d4e5f6', name: 'Thomas', color: '#2563eb' };
const CLAUDE = itemAssistantFor(THOMAS, 'Claude')!;
const STATUSES = [{ status: 'doing~a', name: 'In Progress' }];
const card = (fields: Item['fields'], since = NOW - 2 * 60 * MIN): Item => ({
  id: 'c1',
  type: 'task',
  key: 1,
  rank: 'k',
  fields: { title: 'Write copy', ...fields },
  rev: 1,
  createdAt: 0,
  updatedAt: since,
  createdBy: THOMAS,
  updatedBy: THOMAS,
});
const comment = (text: string, at: number, extra: Record<string, unknown> = {}) => ({
  id: `m${at}`,
  text,
  createdAt: at,
  authorName: 'Thomas',
  authorColor: '#2563eb',
  ai: true as const,
  ...extra,
});
const thread = (comments: ReturnType<typeof comment>[]): CardThread =>
  ({ id: 't', title: 'x', resolved: false, comments, createdAt: 0 }) as unknown as CardThread;
const named = (s: string) => STATUSES.find((c) => c.status === s)?.name;

describe('assistantProgress', () => {
  it('is nothing for a card a person holds, or no one', () => {
    expect(assistantProgress(card({ assignee: THOMAS }), [], named, NOW)).toBeNull();
    expect(assistantProgress(card({}), [], named, NOW)).toBeNull();
  });

  it('says where the card is and for how long, and waits while there is no note', () => {
    const line = assistantProgress(card({ assignee: CLAUDE, status: 'doing~a' }), [], named, NOW);
    expect(line).toEqual({
      assistant: CLAUDE,
      column: 'In Progress for 2 hours',
      note: null,
    });
    expect(assistantProgress(card({ assignee: CLAUDE }), [], named, NOW)?.column).toBeNull();
  });

  it('takes the newest Generated by AI note by its person, first line cut', () => {
    const long = 'x'.repeat(ASSISTANT_NOTE_MAX + 20);
    const line = assistantProgress(
      card({ assignee: CLAUDE }),
      [
        thread([
          comment('Older', NOW - 30 * MIN),
          comment('Thomas by hand', NOW, { ai: undefined }),
        ]),
        thread([
          comment(`${long}\nsecond line`, NOW - 5 * MIN),
          comment('Someone else’s agent', NOW - MIN, { authorName: 'Sam' }),
          comment('   ', NOW - MIN),
        ]),
      ],
      named,
      NOW,
    );
    expect(line?.note?.at).toBe(NOW - 5 * MIN);
    expect(line?.note?.text).toHaveLength(ASSISTANT_NOTE_MAX);
    expect(line?.note?.text.endsWith('…')).toBe(true);
  });

  it('words a span in its largest whole unit', () => {
    expect(spanWords(-5)).toBe('under a minute');
    expect(spanWords(MIN)).toBe('1 minute');
    expect(spanWords(59 * MIN)).toBe('59 minutes');
    expect(spanWords(60 * MIN)).toBe('1 hour');
    expect(spanWords(49 * 60 * MIN)).toBe('2 days');
  });
});

describe('AssistantProgress', () => {
  it('waits for the assistant until it writes, then shows its latest note', () => {
    render(
      <AssistantProgress
        item={card({ assignee: CLAUDE, status: 'doing~a' })}
        statuses={STATUSES}
      />,
    );
    const box = document.querySelector('[data-assistant-progress]')!;
    expect(box.getAttribute('aria-live')).toBe('polite');
    expect(box.textContent).toContain('Waiting for Claude (Thomas)');
    expect(box.textContent).toContain('In Progress for');
    cleanup();
    threadsNow = [thread([comment('Drafted the intro', Date.now() - 5 * MIN)])];
    render(<AssistantProgress item={card({ assignee: CLAUDE })} statuses={STATUSES} />);
    expect(screen.getByText(/Claude \(Thomas\) is on it/)).toBeTruthy();
    expect(document.body.textContent).toMatch(/Latest note .*: Drafted the intro/);
  });

  it('waits, outside a plan that reads its threads', () => {
    threadsNow = NO_CONTEXT;
    render(<AssistantProgress item={card({ assignee: CLAUDE })} statuses={STATUSES} />);
    expect(screen.getByText(/Waiting for Claude \(Thomas\)/)).toBeTruthy();
  });

  it('draws nothing for a person’s card', () => {
    render(<AssistantProgress item={card({ assignee: THOMAS })} statuses={STATUSES} />);
    expect(document.querySelector('[data-assistant-progress]')).toBeNull();
  });
});

describe('the AI mark on a disc, and Assign To', () => {
  it('draws an assistant’s disc with the sparkle, named as one', () => {
    render(<PersonDisc person={CLAUDE} label={assistantLabel(CLAUDE)} />);
    const disc = document.querySelector('[data-assistant-disc]')!;
    expect(disc.querySelector('svg')).not.toBeNull();
    expect(screen.getByLabelText('Claude (Thomas), AI assistant')).toBe(disc);
    cleanup();
    render(<PersonDisc person={THOMAS} />);
    expect(document.querySelector('[data-assistant-disc]')).toBeNull();
  });

  it('offers the assistants after the people in Assign To, and assigns one', () => {
    const onPick = vi.fn();
    render(<AssignMenu people={[THOMAS]} assistants={[CLAUDE]} onPick={onPick} />);
    const rows = screen.getAllByRole('button').map((b) => b.textContent);
    expect(rows.indexOf('Claude (Thomas)')).toBeGreaterThan(rows.indexOf('Thomas'));
    screen
      .getAllByRole('button')
      .find((b) => b.textContent === 'Claude (Thomas)')!
      .click();
    expect(onPick).toHaveBeenCalledWith(CLAUDE);
  });
});
