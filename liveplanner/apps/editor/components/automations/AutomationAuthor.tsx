'use client';

// Automation as an author (docs/specs/026-plan/automations.md "On cards"): a comment or a history line a rule wrote
// shows the bolt disc, "Automation" and the rule's name, on a violet-tinted surface. The rule's name opens its
// builder for an Editor (an Automations scope, and the rule's id: a comment's own, else the rule of that name in the
// plan's live list); for anyone else it is plain text. A comment's link always opens, so a rule made since the list
// was read opens its builder (the screen reads the list again) and one really gone says This Rule Was Deleted. A
// history line has only the name: one the list lacks reads the list again, once per name. Never Generated by AI.

import { useEffect } from 'react';
import { AUTOMATION_PERSON_ID } from '@liveplanner/items';
import { useAutomationsAccess } from './AutomationsContext';
import { readAutomationsFor, useAutomations } from './use-automations';

// A comment a rule added: its public `automation` mark, which survives the api's author-id redaction, or (as a
// history writer or before the mark) the Automation id.
export const isAutomationAuthor = (
  c: { authorId?: string | null; automation?: unknown } | string | undefined | null,
): boolean =>
  typeof c === 'string' || c == null
    ? c === AUTOMATION_PERSON_ID
    : c.automation !== undefined || c.authorId === AUTOMATION_PERSON_ID;

// A comment Automation added: the violet card it sits on.
export const AUTOMATION_SURFACE =
  'rounded-lg bg-brand-50/70 px-2 ring-1 ring-brand-100 dark:bg-brand-500/10 dark:ring-brand-500/20';

export function AutomationAuthorName({
  rule,
  ruleId,
  author = 'Automation',
  className = '',
}: {
  rule: string;
  // The rule's id, where the line carries it (a comment's `automation` mark).
  ruleId?: string | undefined;
  // Who the rule ran for: "GitHub" for a GitHub trigger's run ("GitHub · Move on Merge").
  author?: string;
  className?: string;
}) {
  const access = useAutomationsAccess();
  const scope = access?.scope ?? null;
  const { status, data } = useAutomations(scope, false);
  const id = ruleId ?? data?.rules.find((r) => r.name === rule)?.id;
  // A name the list read lacks: perhaps a rule made since, so the list is read again (once for that name).
  const missing = !ruleId && !!rule && status === 'ready' && id === undefined;
  useEffect(() => {
    if (scope && missing) readAutomationsFor(scope, rule);
  }, [scope, missing, rule]);
  return (
    <span
      data-automation-author=""
      className={`inline-flex min-w-0 items-baseline gap-1 ${className}`}
    >
      <span className="shrink-0 font-semibold text-slate-900 dark:text-slate-50">{author}</span>
      {rule ? (
        <>
          <span aria-hidden className="text-slate-400">
            ·
          </span>
          {access && id ? (
            <button
              type="button"
              onClick={() => access.open({ view: 'rule', ruleId: id })}
              className="truncate font-normal text-brand-700 underline-offset-2 hover:underline dark:text-brand-300"
            >
              {rule}
            </button>
          ) : (
            <span className="truncate font-normal text-slate-500 dark:text-slate-400">{rule}</span>
          )}
        </>
      ) : null}
    </span>
  );
}
