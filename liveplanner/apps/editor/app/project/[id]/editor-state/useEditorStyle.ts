import { usePortalSetters } from '@/hooks/canvas/usePortalSetters';
import { useElementSelectionActions } from '@/hooks/canvas/useElementSelectionActions';
import { useElementStyle } from '@/hooks/canvas/useElementStyle';
import { useStylePreview } from '@/hooks/canvas/useStylePreview';
import { useCleanupPreview } from '@/hooks/canvas/useCleanupPreview';
import type { EditorSelectionSlice } from './useEditorSelection';
import type { EditorProjectSlice } from './useEditorProject';
import type { EditorCollaborationSlice } from './useEditorCollaboration';
import type { EditorPersistenceSlice } from './useEditorPersistence';
import type { EditorPlanDataSlice } from './useEditorPlanData';
import type { EditorCommentsSlice } from './useEditorComments';
import type { EditorEditingSlice } from './useEditorEditing';
import type { EditorTabsSlice } from './useEditorTabs';
import type { EditorTabToolsSlice } from './useEditorTabTools';

// A slice of the editor's state, composed by useEditorState in a fixed order (docs/development/architecture.md
// "The editor's shape"). It takes the slices composed before it and returns what the slices after it, and the
// view (editor-view.ts), read. Its hooks run in the order they did in the one hook this was split from, so the
// effects keep their order.
//
// Selection actions (delete, duplicate, lock, stack), element style, portal links, and the hover previews of
// styles and Tidy Up.
export function useEditorStyle(
  selectionSlice: EditorSelectionSlice,
  projectSlice: EditorProjectSlice,
  collaborationSlice: EditorCollaborationSlice,
  persistenceSlice: EditorPersistenceSlice,
  planDataSlice: EditorPlanDataSlice,
  commentsSlice: EditorCommentsSlice,
  editingSlice: EditorEditingSlice,
  tabsSlice: EditorTabsSlice,
  tabToolsSlice: EditorTabToolsSlice,
) {
  const { activeId, readSelection, setEditingId, setMultiSelectedIds, setSelectedId } =
    selectionSlice;
  const { commitTabs, previewingRef, tabs, tickTabs } = projectSlice;
  const { contextMenu } = collaborationSlice;
  const { tabsRef } = persistenceSlice;
  const { activeTab } = planDataSlice;
  const { lockedByOther } = commentsSlice;
  const {
    commit,
    commitActiveTab,
    editsBlocked,
    layerInertIds,
    layerLockedIds,
    rememberingCommit,
    rememberingTickTabs,
    structureBlocked,
    styleMemory,
  } = editingSlice;
  const { currentSelectionIds, selectionPrimary } = tabsSlice;
  const { checkpointBurst, elementDeleteGuard } = tabToolsSlice;
  // Structural element operations (delete, marquee commit, lock, and the
  // duplicate family). They change the element set
  // and/or the selection rather than element fields; see
  // useElementSelectionActions.
  const {
    deleteSelected,
    selectMarquee,
    toggleLockMultiSelected,
    duplicateMultiSelected,
    deleteMultiSelected,
    narrowMultiSelection,
    duplicateSelected,
    stackSelectedFront,
    stackSelectedBack,
    spawnConnectSelected,
  } = useElementSelectionActions({
    sheetDeleteGuard: elementDeleteGuard,
    currentSelectionIds,
    readSelection,
    activeTab,
    commit,
    setSelectedId,
    setEditingId,
    setMultiSelectedIds,
    lockedByOther,
    layerLockedIds,
    layerInertIds,
  });

  // Element styling / layering actions (lock, layer order, text size /
  // align / style, fill / stroke / text colour, opacity, padding, the
  // arrow + border presets, shape-kind morph, reset-to-theme). All
  // mutate the current selection; see useElementStyle.
  const {
    toggleLockSelected,
    toggleAspectLockSelected,
    bringSelectedToFront,
    sendSelectedToBack,
    setTextSizeSelected,
    setTextAlignSelected,
    setLaneUprightTitleSelected,
    setFontSelected,
    toggleTextStyleSelected,
    setFillColorSelected,
    setStrokeColorSelected,
    setTextColorSelected,
    setOpacitySelected,
    setShadowSelected,
    setPaddingSelected,
    setIconSizeSelected,
    setArrowEndsSelected,
    setArrowThicknessSelected,
    setArrowheadSizeSelected,
    setArrowheadShapeSelected,
    setTableHeaderRowSelected,
    setTableHeaderColumnSelected,
    setTableZebraSelected,
    setHeaderFillSelected,
    burstSelectedStyle,
    setArrowheadColorSelected,
    setLabelFillSelected,
    setTableHeaderTextColorSelected,
    setArrowStyleSelected,
    setArrowStrokeStyleSelected,
    setArrowRouteBehindSelected,
    setArrowExactStartSelected,
    setShapeKindSelected,
    resetAspectRatioSelected,
    setSizeSelected,
    setRotationSelected,
    setBorderStrokeSelected,
    setBorderStyleSelected,
    setBorderRadiusSelected,
    setMarkerSelected,
    setMarkerSizeSelected,
    appendTableRowSelected,
    appendTableColumnSelected,
    setCodeSelected,
    setCodeWrapSelected,
    setLegendItemsSelected,
    setPageHeading,
    setWebRows,
    appendWebRowTo,
    setWebRowsSelected,
    setHeroCaptionLine,
    setHeroCaptionSelected,
    setChecklistItemsSelected,
    setDecisionStatusSelected,
    setDecisionDateSelected,
    setDecisionDriversSelected,
    setRatingSelected,
    setRatingAnimSelected,
    setRatingAnimSpeedSelected,
    setRatingAnimRepeatSelected,
    setPieDataSelected,
    setPieAnimSelected,
    setPieAnimSpeedSelected,
    setPieAnimRepeatSelected,
    setChartLegendSelected,
    setChartValuesSelected,
    setChartAxisSelected,
    setChartRightAxisSelected,
    setChartLegendPositionSelected,
    setChartTypeSelected,
    unlinkChartSelected,
    setLineDataSelected,
    sankey,
    sequence,
    resetShapeStyleSelected,
    resetArrowStyleSelected,
    setArrowFlowSelected,
    setIconAnimationSelected,
    setIconAnimationSpeedSelected,
    setProgressSelected,
    setProgressAnimSelected,
    setProgressAnimSpeedSelected,
    setProgressAnimRepeatSelected,
    setFlowSpeedSelected,
    setIconAnimationRepeatSelected,
    setFlowRepeatSelected,
    resetColorsSelected,
  } = useElementStyle({
    currentSelectionIds,
    selectionPrimary,
    readSelection,
    activeTab,
    activeId,
    editsBlocked,
    // Every style setter the context menu reaches records into style memory.
    commit: rememberingCommit,
    commitActiveTab,
    tickTabs: rememberingTickTabs,
    checkpointBurst,
  });

  // Portal links (docs/specs/009-elements/portal-element.md) live off the style hook: a link can point at a
  // portal on ANOTHER tab, so these setters need the whole tab list and a
  // tabs-wide commit rather than the active tab's element mapper.
  const {
    setPortalTargetSelected,
    setPortalNameSelected,
    createLinkedPortal,
    setSessionConfigSelected,
    setPickerSourceSelected,
    setPickerOptionsSelected,
  } = usePortalSetters({
    currentSelectionIds,
    contextTargetId: contextMenu?.mode === 'element' ? contextMenu.elementId : null,
    commitTabs,
    tabs,
    activeId,
    setSelectedId,
  });

  // Hover-to-preview for the style-preset tiles (docs/specs/010-palette/style-presets.md): hovering a preset on
  // a desktop pointer shows it live; the change only sticks on click. See
  // useStylePreview — preview/revert go through tickTabs (no history), the
  // commit restores the original first so undo snapshots the true pre-hover
  // state.
  const {
    clearPreview: clearStylePreview,
    previewElementStyle,
    commitElementStyle,
    previewShapeColorPreset,
    commitShapeColorPreset,
    previewArrowPreset,
    commitArrowPreset,
    previewArrowFlow,
    commitArrowFlow,
    previewIconAnimation,
    commitIconAnimation,
    previewFillColor,
    previewCodeTheme,
    commitCodeTheme,
    previewTablePreset,
    commitTablePreset,
    previewChartPalette,
    commitChartPalette,
    previewLabelFill,
    commitLabelFill,
    previewHeaderFill,
    previewArrowheadColor,
    commitFillColor,
    commitHeaderFill,
    commitArrowheadColor,
    previewStrokeColor,
    commitStrokeColor,
    previewTextColor,
    commitTextColor,
    previewBorderStroke,
    commitBorderStroke,
    previewBorderStyle,
    commitBorderStyle,
    previewBorderRadius,
    commitBorderRadius,
    previewShadow,
    commitShadow,
    previewFinish,
    commitFinish,
    previewRotation,
    commitRotation,
    previewShapeKind,
    commitShapeKind,
    previewIconSize,
    commitIconSize,
    previewIconWeight,
    commitIconWeight,
    previewMarker,
    commitMarker,
    previewMarkerSize,
    commitMarkerSize,
    previewTextAlign,
    commitTextAlign,
    previewTextSize,
    commitTextSize,
    previewFont,
    commitFont,
    previewPadding,
    commitPadding,
    previewInlineIcon,
    commitInlineIcon,
  } = useStylePreview({
    editsBlocked,
    activeId,
    currentSelectionIds,
    tabsRef,
    tickTabs,
    commitTabs,
    previewingRef,
    onCommitted: styleMemory.recordEdit,
  });

  // The same idea one level up (docs/specs/008-canvas/layout-cleanup.md "Hover to see it first"):
  // hovering a Tidy Up tile lays the whole tab out behind the popover, and it only sticks on press.
  const { previewCleanup, endCleanupPreview, assessCleanupKind } = useCleanupPreview({
    editsBlocked: structureBlocked,
    activeId,
    tabsRef,
    tickTabs,
    previewingRef,
  });
  return {
    appendTableColumnSelected,
    appendTableRowSelected,
    appendWebRowTo,
    assessCleanupKind,
    bringSelectedToFront,
    burstSelectedStyle,
    clearStylePreview,
    commitArrowFlow,
    commitArrowPreset,
    commitArrowheadColor,
    commitBorderRadius,
    commitBorderStroke,
    commitBorderStyle,
    commitChartPalette,
    commitCodeTheme,
    commitElementStyle,
    commitFillColor,
    commitFinish,
    commitFont,
    commitHeaderFill,
    commitIconAnimation,
    commitIconSize,
    commitIconWeight,
    commitInlineIcon,
    commitLabelFill,
    commitMarker,
    commitMarkerSize,
    commitPadding,
    commitRotation,
    commitShadow,
    commitShapeColorPreset,
    commitShapeKind,
    commitStrokeColor,
    commitTablePreset,
    commitTextAlign,
    commitTextColor,
    commitTextSize,
    createLinkedPortal,
    deleteMultiSelected,
    deleteSelected,
    duplicateMultiSelected,
    duplicateSelected,
    endCleanupPreview,
    narrowMultiSelection,
    previewArrowFlow,
    previewArrowPreset,
    previewArrowheadColor,
    previewBorderRadius,
    previewBorderStroke,
    previewBorderStyle,
    previewChartPalette,
    previewCleanup,
    previewCodeTheme,
    previewElementStyle,
    previewFillColor,
    previewFinish,
    previewFont,
    previewHeaderFill,
    previewIconAnimation,
    previewIconSize,
    previewIconWeight,
    previewInlineIcon,
    previewLabelFill,
    previewMarker,
    previewMarkerSize,
    previewPadding,
    previewRotation,
    previewShadow,
    previewShapeColorPreset,
    previewShapeKind,
    previewStrokeColor,
    previewTablePreset,
    previewTextAlign,
    previewTextColor,
    previewTextSize,
    resetArrowStyleSelected,
    resetAspectRatioSelected,
    resetColorsSelected,
    resetShapeStyleSelected,
    sankey,
    selectMarquee,
    sendSelectedToBack,
    sequence,
    setArrowEndsSelected,
    setArrowExactStartSelected,
    setArrowFlowSelected,
    setArrowRouteBehindSelected,
    setArrowStrokeStyleSelected,
    setArrowStyleSelected,
    setArrowThicknessSelected,
    setArrowheadColorSelected,
    setArrowheadShapeSelected,
    setArrowheadSizeSelected,
    setBorderRadiusSelected,
    setBorderStrokeSelected,
    setBorderStyleSelected,
    setChartAxisSelected,
    setChartLegendPositionSelected,
    setChartLegendSelected,
    setChartRightAxisSelected,
    setChartTypeSelected,
    setChartValuesSelected,
    setChecklistItemsSelected,
    setCodeSelected,
    setCodeWrapSelected,
    setDecisionDateSelected,
    setDecisionDriversSelected,
    setDecisionStatusSelected,
    setFillColorSelected,
    setFlowRepeatSelected,
    setFlowSpeedSelected,
    setFontSelected,
    setHeaderFillSelected,
    setHeroCaptionLine,
    setHeroCaptionSelected,
    setIconAnimationRepeatSelected,
    setIconAnimationSelected,
    setIconAnimationSpeedSelected,
    setIconSizeSelected,
    setLabelFillSelected,
    setLaneUprightTitleSelected,
    setLegendItemsSelected,
    setLineDataSelected,
    setMarkerSelected,
    setMarkerSizeSelected,
    setOpacitySelected,
    setPaddingSelected,
    setPageHeading,
    setPickerOptionsSelected,
    setPickerSourceSelected,
    setPieAnimRepeatSelected,
    setPieAnimSelected,
    setPieAnimSpeedSelected,
    setPieDataSelected,
    setPortalNameSelected,
    setPortalTargetSelected,
    setProgressAnimRepeatSelected,
    setProgressAnimSelected,
    setProgressAnimSpeedSelected,
    setProgressSelected,
    setRatingAnimRepeatSelected,
    setRatingAnimSelected,
    setRatingAnimSpeedSelected,
    setRatingSelected,
    setRotationSelected,
    setSessionConfigSelected,
    setShadowSelected,
    setShapeKindSelected,
    setSizeSelected,
    setStrokeColorSelected,
    setTableHeaderColumnSelected,
    setTableHeaderRowSelected,
    setTableHeaderTextColorSelected,
    setTableZebraSelected,
    setTextAlignSelected,
    setTextColorSelected,
    setTextSizeSelected,
    setWebRows,
    setWebRowsSelected,
    spawnConnectSelected,
    stackSelectedBack,
    stackSelectedFront,
    toggleAspectLockSelected,
    toggleLockMultiSelected,
    toggleLockSelected,
    toggleTextStyleSelected,
    unlinkChartSelected,
  };
}

export type EditorStyleSlice = ReturnType<typeof useEditorStyle>;
